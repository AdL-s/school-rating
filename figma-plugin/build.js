// Builds code.js = school photos (base64) + src/plugin.js
// Run:  node build.js
const fs = require('fs');
const path = require('path');

const imgDir = path.join(__dirname, '..', 'assets', 'img');
const names = ['smichovska', 'jaroska', 'oa-bati', 'supsuh', 'spss-olomouc', 'wichterlovo',
  'spss-plzen', 'szs-ostrava', 'gjkt', 'hero-keplera'];

const images = {};
for (const n of names) images[n] = fs.readFileSync(path.join(imgDir, n + '.jpg')).toString('base64');

const src = fs.readFileSync(path.join(__dirname, 'src', 'plugin.js'), 'utf8');
const out = '// Generated by build.js. Edit src/plugin.js, then run: node build.js\n' +
  'const IMAGES = ' + JSON.stringify(images) + ';\n\n' + src;

fs.writeFileSync(path.join(__dirname, 'code.js'), out);
console.log('code.js written (' + Math.round(out.length / 1024) + ' KB, ' + names.length + ' photos)');
